package bot

import "math"

// Цена команды в баллах.
//
// До 24.10.2026 всё стоило одну «генерацию»: ролик обходился человеку ровно
// как правка картинки, хотя занимает карту в девять раз дольше. Баллы это
// выправляют — один балл это пятнадцать секунд карты.
//
// Числа замерены, а не придуманы: 846 задач за восемь суток, медианы.
//
//	правка картинки      14 с  →  1 балл
//	картинка с нуля      31 с  →  2 балла
//	ролик 5 секунд      130 с  → 10 баллов
//	стикер в пачке       14 с  →  1 балл (пачка из десяти — десять)
const (
	pointsEdit    = 1
	pointsImage   = 2
	pointsVideo   = 10
	pointsSticker = 1
)

// videoLengthExponent: удвоение длины ролика стоит ВТРОЕ дороже, а не вдвое.
//
// Замер на одном и том же холсте 672x896: пять секунд (124 кадра) — 178 с
// карты, десять секунд (243 кадра) — 538 с. Отсюда показатель log2(3) — при
// нём цена повторяет замер, а не приближает его.
//
// Холст в цену НЕ входит, хотя время линейно по пикселям (0,285 с на
// килопиксель). Холст выбираем мы под пропорции присланной фотографии, и
// платить за наш выбор человеку нечем объяснить: разброс ±40% берём на себя
// ради того, чтобы цену можно было назвать заранее.
const videoLengthExponent = 1.5849625007211562 // log2(3)

// aiPoints is what one command of this kind costs.
//
// Неизвестный вид стоит один балл, а не ноль: команда, забытая в этой
// таблице, иначе станет бесплатной дырой, и заметит это не тот, кто надо.
func aiPoints(kind string) int {
	switch kind {
	case aiKindEdit:
		return pointsEdit
	case aiKindImage:
		return pointsImage
	case aiKindVideo:
		return aiVideoPoints(videoSecondsDefault)
	case aiKindSticker:
		return pointsSticker
	}

	return 1
}

// aiVideoPoints is what a clip of this length costs. Выходит 5 с — 10 баллов,
// 10 с — 30, 15 с — 57.
//
// Длину человек просит словами (cutVideoSeconds), и там же она зажимается в
// 5..15 секунд. Считать надо именно по зажатому числу: иначе попросят минуту,
// получат пятнадцать секунд, а в счёт попадёт минута. Ноль значит, что длины
// не просили, и цена выходит обычная.
//
// СВЕРКА 27.10.2026, как и было обещано этим комментарием. Пятнадцать секунд
// замерены: один узел, один холст 672x896, один промпт и сид, подряд — пять
// секунд 138 с карты, пятнадцать 700 с. Втрое длиннее вышло ровно впятеро
// дороже, то есть показатель по этой паре 1.48, а не 1.585.
//
// Показатель оставлен прежним СОЗНАТЕЛЬНО: при 1.585 ролик на пятнадцать
// секунд стоит 57 баллов вместо 49 по замеру, то есть на 16% дороже
// себестоимости. Цену назначает хозяин, а не замер; ошибаться в эту сторону
// дешевле, и длинный ролик всё ещё самое тяжёлое, что бот умеет.
func aiVideoPoints(seconds float64) int {
	if seconds <= videoSecondsDefault {
		return pointsVideo
	}

	return int(math.Round(pointsVideo *
		math.Pow(seconds/videoSecondsDefault, videoLengthExponent)))
}
